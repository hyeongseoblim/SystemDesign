SET content_md = $boundary_review$## 1. 배포 단위와 데이터 소유권을 나눠 본다

Modular Monolith는 하나의 배포 단위 안에서 모듈 경계를 지키는 구조다. MSA는 서비스별 변경·배포·운영의 독립성을 지향한다. 프로세스 개수만 늘려도 독립성이 생기는 것은 아니다. 내부 API를 우회하는 테이블 접근과 동시에 올려야 하는 버전 의존성이 남으면 분산된 채로 함께 변경해야 한다.

**서비스별 데이터 소유권은 서비스마다 물리 DB 서버 한 대를 둔다는 뜻이 아니다.** 같은 서버의 별도 스키마·테이블과 접근 권한으로 논리적 소유권을 지킬 수 있다. 반대로 서버를 분리해도 다른 서비스의 내부 스키마에 직접 의존하면 결합이 남는다. 공유 서버의 자원 경합과 장애 범위는 별도 평가한다.

```mermaid
flowchart LR
    O[주문 서비스] --> OS[주문 소유 스키마]
    I[재고 서비스] --> IS[재고 소유 스키마]
    O -->|예약 계약| I
    OS -.-> DB[같은 물리 DB 서버도 가능]
    IS -.-> DB
```

> **첫 질문의 전제**
>
> “DB 공유”가 동일 물리 서버인지, 동일 테이블을 여러 서비스가 직접 읽고 쓰는 것인지 먼저 구분한다. 후자는 스키마 변경·업무 규칙·배포를 결합시키기 쉽다. 물리적 공유만으로 즉시 Distributed Monolith라고 확정하지 않는다.

## 2. 비교는 목표와 측정값으로 한다

| 관점 | Modular Monolith | MSA에서 추가로 검토할 것 |
|---|---|---|
| 배포 | 단일 배포물의 변경 조정 | 독립 배포를 허용하는 API·데이터 호환 |
| 정합성 | 같은 DB 트랜잭션을 쓰기 쉬움 | 경계를 넘는 불변 조건·예약·보상 |
| 확장 | 배포물 단위 복제, 내부 작업 분리도 가능 | 서비스별 병목과 독립 용량 |
| 장애 | 프로세스·공유 자원의 영향 | 네트워크·공유 DB·호출 체인의 전파 |
| 운영 | 상대적으로 적은 배포 단위 | 관측·인증·릴리스·온콜·복구 비용 |

팀 수가 몇 개면 반드시 MSA라는 기준은 없다. 한 팀이 여러 서비스를 운영할 수도 있고 여러 팀이 모듈러 모놀리스에 기여할 수도 있다. 조직의 책임 경계와 시스템 경계가 서로 영향을 준다는 관찰을 팀 수=서비스 수 공식으로 바꾸지 않는다.

독립 배포를 막는 변경 빈도, 한 요청의 왕복 호출 수, 종단 지연, 모듈별 부하와 복구 시간을 측정한다. 여러 서비스가 함께 바뀌는 기능 하나가 있다는 이유만으로 경계가 틀렸다고 단정하지 않는다. 반복적으로 작은 변경도 동시 배포를 강제하는지 본다. 기업 이름이나 검증되지 않은 성능 배수를 분리 근거로 사용하지 않는다.

## 3. 직렬 체인의 가용성을 계산하는 전제

다섯 서비스가 모두 성공해야 요청이 성공하고, 각 성공 확률이 같은 기준으로 0.999이며 서로 독립이라고 **가정**하면 다음과 같다.

```python
availability = 0.999 ** 5
unavailable_hours = (1 - availability) * 365 * 24
print(f"{availability * 100:.4f}%")  # 99.5010%
print(f"{unavailable_hours:.2f} hours/year")  # 43.71 hours/year
```

시간 기준 가용성을 365일에 적용한 환산값이다. 요청 성공률 SLI를 측정했다면 그 실패 비율을 실제 연간 장애 시간으로 곧바로 바꿀 수 없다. 공통 DB·영역·배포 장애로 실패가 상관되거나 일부 단계가 선택적이면 단순 곱셈 모델이 달라진다. 완전히 같은 시점에만 다섯 서비스가 실패한다면 각 99.9%여도 전체는 99.9%다.

각 단계 p99가 20ms라는 정보만으로 종단 p99를 100ms 또는 그 이상이라고 확정할 수도 없다. 단계별 분포와 상관관계가 필요하다. 100개 요청에서 각 서비스의 느린 요청이 같은 요청에 몰리는 경우와 서로 다른 요청에 흩어지는 경우는 종단 꼬리가 다르다. 같은 부하의 분산 추적으로 종단 지연을 직접 측정한다.

| 개선 패턴 | 무엇을 개선하나 | 보장하지 않는 것 |
|---|---|---|
| 필수 아닌 작업을 비동기로 분리 | 응답의 직렬 의존 감소 | 후속 업무가 즉시 완료됨 |
| Timeout·Circuit Breaker·Bulkhead | 대기·자원 고갈·전파 제한 | 필수 하류의 업무 성공 복원 |
| 계약에 맞는 캐시·대체 결과 | 일부 기능의 저하 상태 응답 | 오래된 재고로 확정 예약해도 안전함 |

재시도는 일시 실패에서 도움이 될 수 있지만 요청 기한, 횟수 제한, 지터, 멱등성을 함께 둔다. 실패한 필수 결제를 성공이라고 표시하는 Fallback은 가용성 개선이 아니라 잘못된 업무 결과다.

## 4. 데이터 소유권을 옮기면 생기는 문제

가상 주문·재고 모듈을 분리하면 기존의 단일 트랜잭션이 주문 저장과 재고 예약을 함께 확정하지 못할 수 있다. 재고의 권위 있는 쓰기 주체를 정하고, 주문은 예약 요청과 결과를 통해 상태를 전이한다. 승인 대기·예약 실패·보상 대기 상태를 숨기지 않는다.

Outbox는 한 서비스의 업무 변경과 발행 의도를 묶는다. Saga는 여러 로컬 커밋의 진행과 보상을 관리한다. 둘을 도입했다고 모든 서비스의 상태가 동시에 보이는 것은 아니다. 조회를 API 조합으로 할지, 이벤트 기반 읽기 모델로 할지도 신선도와 실패 요구에 따라 정한다.

다른 서비스가 보유한 읽기 복제본은 독립적인 진실의 원천이 아니다. 데이터별 소유자, 조회 모델의 지연, 정정·재생 경로를 계약으로 남긴다. 이전 중에는 옛 시스템과 새 시스템 양쪽에서 같은 업무 키를 동시에 쓰지 않도록 통제한다.

## 5. 가상 물류 시스템의 Strangler Fig 이전

아래는 주문·결제·재고의 결합이 높고 배송 조회 읽기 부하가 큰 상황에 대한 **가상 순서**다. 모든 회사에 같은 순서를 적용하지 않는다.

1. 기존 모듈의 데이터 접근과 호출을 조사하고 외부 계약·성공 기준을 정한다.
2. 배송 조회 모델을 먼저 분리해 과거 데이터 백필과 후속 변경을 연결한다. 동일 시점·버전으로 비교해 누락·중복·지연을 검증한다.
3. 일부 조회 트래픽을 새 경로로 전환하고 오류·지연·상태 일치를 관찰한다. 읽기 결과만 비교하는 Shadow 요청이 외부 쓰기를 일으키지 않게 한다.
4. 쓰기 기능은 소유권 이전을 별도 단계로 다룬다. 이전 쓰기를 차단하고 진행 중 요청·변경 로그를 정리한 뒤 새 소유자로 전환한다. 요청 키와 재시도 경로를 유지한다.
5. 옛 배치·보고서·관리 도구까지 의존성이 사라지고 복구 기간이 지난 뒤 이전 저장소와 코드를 정리한다.

```mermaid
flowchart TD
    C[클라이언트] --> F[라우팅 계층]
    F -->|미이전 기능| M[기존 모놀리스]
    F -->|검증한 조회| N[신규 조회 서비스]
    M -->|백필과 후속 변경| N
    N --> V[동일 기준 상태 대조]
```

주문·결제·재고를 나중에 두는 이유는 이 가정에서 불변 조건과 보상이 복잡하기 때문이다. 실제 병목이나 변경 요구가 핵심 영역에 있고 경계가 검증됐다면 먼저 분리할 수도 있다. 정산 역시 금전·감사 정합성이 얽힐 수 있어 “배치라서 쉬운 첫 후보”로 단정하지 않는다.

## 6. 롤백은 데이터까지 포함한다

신규 경로에서 쓰기가 발생한 뒤 옛 DB가 뒤처져 있다면 프록시를 원복하는 것만으로 안전하게 돌아갈 수 없다. 되돌릴 수 있는 마지막 시점, 역방향 데이터 동기화·대사, 양쪽 버전의 스키마 호환, 외부 효과 복구를 준비한다. 되돌리는 것보다 수정 배포가 안전한 구간도 명시한다.

```text
분리 결정 기록
- 독립 배포·확장으로 해결하려는 실제 문제와 측정 기준
- 데이터 소유자, 불변 조건, API/이벤트 호환 계약
- 백필 기준점, 후속 변경 연결, 쓰기 소유권 전환 절차
- 부분 실패, 복구 기한, 롤백 가능 구간과 대사 담당자
- 전환 중단 기준과 옛 의존성 제거 확인
```

이 문서의 가용성 계산은 가정한 모델의 산술 검증이다. 실제 시스템 부하·장애 시험이나 기업별 도입 사례 검증을 대신하지 않는다.

